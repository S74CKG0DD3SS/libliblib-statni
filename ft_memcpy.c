#include "libft.h"

void	*ft_memcpy(void *dest, const void *src, size_t n)
{
	size_t		i;
	char		*r;
	const char	*s;

	r = (char *)dest;
	s = (const char *)src;
	i = 0;
	while (i < n)
	{
		*r = *s;
		s++;
		r++;
		i++;
	}
	return (dest);
}
